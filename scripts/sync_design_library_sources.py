#!/usr/bin/env python3
"""Build the single Design Library from the three canonical repositories."""
from __future__ import annotations
import argparse
import copy
import hashlib
import json
from pathlib import Path
import library_email_sources as email
import library_lp_sources as lp
from library_token_sources import build_tokens_snapshot

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT
DEFAULT_DESIGN_SYSTEM = ROOT.parent / 'design-system'
MARKER = 'window.designLibraryData = '
HEADER = '// Generated by scripts/sync_design_library_sources.py. Do not edit manually.\n'

def read_data(path):
    return json.loads(path.read_text().split(MARKER, 1)[1].strip().removesuffix(';'))

def generate(email_dir, lp_dir, email_only=False, design_system_dir=DEFAULT_DESIGN_SYSTEM):
    email_dir, lp_dir = Path(email_dir), Path(lp_dir)
    tokens_path = Path(design_system_dir) / 'tokens/brands/immoscout24.json'
    email.configure_source(email_dir)
    modules = email.build_email_modules_map()
    navigation = json.loads((ROOT / 'library-data/email-navigation.json').read_text())
    for item in navigation['items']:
        builder = email.build_service_products_library_html if item['kind'] == 'serviceProducts' else email.build_email_library_html
        item['libraryHtml'] = builder(item, modules)
    selected = {m for item in navigation['items'] for m in item.get('modules', [])}
    if selected != set(modules):
        raise ValueError('Email navigation/source mismatch: ' + str(selected ^ set(modules)))
    outputs = {}
    if email_only:
        data = read_data(OUTPUT / 'content-data.js')
        if list(data['sections']) != ['email', 'lp', 'tokens']:
            raise ValueError('Run a full sync before --email-only.')
        data = copy.deepcopy(data)
        data['sections']['email'] = navigation
    else:
        lp.configure_source(lp_dir, tokens_path)
        lp_section = lp.build_lp_content_section(lp.load_module_metadata())
        lp_section['label'] = 'LP-Module'
        tokens = json.loads((tokens_path).read_text())
        token_snapshot = build_tokens_snapshot(tokens)
        data = {'sections': {'email': navigation, 'lp': lp_section, 'tokens': {
            'label': 'Design-Tokens', 'items': [{'id': key, 'label': label, 'kind': 'tokens'} for key, label in [
                ('colors', 'Colors'), ('typography', 'Typography'), ('spacing', 'Spacing'),
                ('radius', 'Border Radius'), ('borders', 'Borders'), ('ratios', 'Image Ratios')]]}},
            'lpElements': lp.build_lp_element_data(), 'tokens': token_snapshot}
        markup = lp.extract_module_markup(lp.SELECTED_LP_MODULE_IDS)
        outputs['lp-module-markup.js'] = lp.render_markup_assignment(markup)
        outputs['lp-shadow-styles.js'] = lp.render_shadow_assignment(lp.build_lp_shadow_styles())
        data['lpStylesheets'] = lp.PUBLIC_STYLESHEETS
    data['serviceProducts'] = email.build_service_products()
    outputs['content-data.js'] = HEADER + MARKER + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    outputs['email-preview-styles.css'] = (email_dir / 'modules/preview.css').read_text()
    outputs['manifest.json'] = render_manifest(outputs)
    return outputs

def render_manifest(outputs=None):
    # Hash the deployed snapshot only; no private paths or credentials in public output.
    outputs = outputs or {}
    names = ['content-data.js', 'email-preview-styles.css', 'lp-module-markup.js',
             'lp-shadow-styles.js', 'index.html', 'app.js', 'styles.css']
    snapshot = {name: outputs[name] if name in outputs else (OUTPUT / name).read_text()
                for name in names}
    data = json.loads(snapshot['content-data.js'].split(MARKER, 1)[1].strip().removesuffix(';'))
    manifest = {'name': 'Design Library', 'sections': list(data['sections']), 'moduleCounts': {
        'email': len({m for item in data['sections']['email']['items'] for m in item.get('modules', [])}),
        'lp': sum(len(item.get('modules', [])) for item in data['sections']['lp']['items'])}}
    manifest['buildDigest'] = hashlib.sha256(json.dumps(
        snapshot, sort_keys=True, ensure_ascii=False).encode()).hexdigest()
    return json.dumps(manifest, ensure_ascii=False, indent=2) + '\n'

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--email-builder-dir', type=Path, default=ROOT.parent / 'email-builder')
    parser.add_argument('--lp-builder-dir', type=Path, default=ROOT.parent / 'lp-builder')
    parser.add_argument('--design-system-dir', type=Path, default=DEFAULT_DESIGN_SYSTEM)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--email-only', action='store_true')
    modes.add_argument('--refresh-manifest', action='store_true', help='Refresh the fingerprint of existing files without reading source repositories.')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = ({'manifest.json': render_manifest()} if args.refresh_manifest else
               generate(args.email_builder_dir, args.lp_builder_dir, args.email_only, args.design_system_dir))
    allowed = {'content-data.js', 'lp-module-markup.js', 'lp-shadow-styles.js', 'email-preview-styles.css', 'manifest.json'}
    if not set(outputs).issubset(allowed):
        raise ValueError('Generator output must be an approved snapshot file.')
    if any((OUTPUT / name).is_symlink() for name in outputs):
        raise ValueError('Refusing symlink output.')
    drift = []
    for name, content in outputs.items():
        path = OUTPUT / name
        if not path.exists() or path.read_text() != content:
            drift.append(name)
            if not args.check:
                path.write_text(content)
    if args.check and drift:
        raise SystemExit('Generated files differ: ' + ', '.join(drift))
    print('Design Library: ' + ('checked' if args.check else 'generated') + f' ({len(outputs)} files).')

if __name__ == '__main__':
    main()
